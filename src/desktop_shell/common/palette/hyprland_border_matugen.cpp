void sync_hyprland_border_matugen(const eh::config::ShellAppearance& a) {
  if (std::getenv("HYPRLAND_INSTANCE_SIGNATURE") == nullptr) return;
  if (env_disables_hypr_matugen_border()) return;
  if (!a.anyPaletteActive()) return;
  if (a.matugenThemingEnabled && !a.matugenOutputs.hyprland) return;

  const auto mc = eh::config::derived_chrome_colors(a);

  const std::string active1 = hypr_rgba(mc.accentR, mc.accentG, mc.accentB, 0.92f);
  const std::string active2 =
      hypr_rgba(mc.accentR * 0.82f, mc.accentG * 0.82f, mc.accentB * 0.82f, 0.70f);
  const std::string inactive =
      hypr_rgba(mc.outlineR, mc.outlineG, mc.outlineB, 0.42f);
  const std::string locked =
      hypr_rgba(mc.notifCriticalOutlineR, mc.notifCriticalOutlineG, mc.notifCriticalOutlineB, 1.0f);

  const std::string ac_gradient = active1 + " " + active2 + " 45deg";

  if (wspace::hyprland::hyprland_config_is_lua()) {
    const char* home = std::getenv("HOME");
    if (home) {
      const std::string dir = std::string(home) + "/.config/hypr/hyprland";
      std::filesystem::create_directories(dir);
      const std::string path = dir + "/colors.lua";
      const std::string content =
          "-- Generated by Event Horizon\n"
          "hl.config({\n"
          "  general = {\n"
          "    col = {\n"
          "      active_border   = { colors = { \"" + active1 + "\", \"" + active2 + "\" }, angle = 45 },\n"
          "      inactive_border = \"" + inactive + "\"\n"
          "    }\n"
          "  },\n"
          "  group = {\n"
          "    col = {\n"
          "      border_active          = { colors = { \"" + active1 + "\", \"" + active2 + "\" }, angle = 45 },\n"
          "      border_inactive        = \"" + inactive + "\",\n"
          "      border_locked_active   = \"" + locked + "\",\n"
          "      border_locked_inactive = \"" + inactive + "\"\n"
          "    },\n"
          "    groupbar = {\n"
          "      col = {\n"
          "        active          = { colors = { \"" + active1 + "\", \"" + active2 + "\" }, angle = 45 },\n"
          "        inactive        = \"" + inactive + "\",\n"
          "        locked_active   = \"" + locked + "\",\n"
          "        locked_inactive = \"" + inactive + "\"\n"
          "      }\n"
          "    }\n"
          "  }\n"
          "})\n";
      if (FILE* f = std::fopen(path.c_str(), "w")) {
        std::fwrite(content.data(), 1, content.size(), f);
        std::fclose(f);
      }
    }
    (void)hyprland_ipc_send("reload");
  } else {
    keyword_set("general:col.active_border", "general/col/active_border", ac_gradient);
    keyword_set("general:col.inactive_border", "general/col/inactive_border", inactive);
    keyword_set("group:col.border_active", "group/col/border_active", ac_gradient);
    keyword_set("group:col.border_inactive", "group/col/border_inactive", inactive);
    keyword_set("group:col.border_locked_active", "group/col/border_locked_active", locked);
    keyword_set("group:col.border_locked_inactive", "group/col/border_locked_inactive", inactive);
    keyword_set("group:groupbar:col.active", "group/groupbar/col/active", ac_gradient);
    keyword_set("group:groupbar:col.inactive", "group/groupbar/col/inactive", inactive);
    keyword_set("group:groupbar:col.locked_active", "group/groupbar/col/locked_active", locked);
    keyword_set("group:groupbar:col.locked_inactive", "group/groupbar/col/locked_inactive", inactive);
  }
}
