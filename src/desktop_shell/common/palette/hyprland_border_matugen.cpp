bool env_disables_hypr_matugen_border() {
  const char* e = std::getenv("EH_HYPR_MATUGEN_BORDER");
  if (e == nullptr || e[0] == '\0') return false;
  if (e[0] == '0' && e[1] == '\0') return true;
  std::array<char, 16> buf{};
  for (size_t i = 0; i < buf.size() - 1 && e[i] != '\0'; ++i) buf[i] = static_cast<char>(std::tolower(static_cast<unsigned char>(e[i])));
  return std::strcmp(buf.data(), "off") == 0 || std::strcmp(buf.data(), "false") == 0 || std::strcmp(buf.data(), "no") == 0;
}

std::string hypr_rgba(float r, float g, float b, float a) {
  auto u = [](float x) -> int {
    return static_cast<int>(std::clamp(x, 0.f, 1.f) * 255.f + 0.5f);
  };
  std::array<char, 24> out;
  std::snprintf(out.data(), out.size(), "0x%02x%02x%02x%02x", u(a), u(r), u(g), u(b));
  return out.data();
}

bool keyword_set(const std::string& key_colon, const std::string& key_slash, const std::string& value) {
  auto try_key = [&](const std::string& key) -> bool {
    auto resp = hyprland_ipc_request("keyword " + key + " " + value);
    if (!resp) return false;
    while (!resp->empty() && static_cast<unsigned char>(resp->back()) <= ' ')
      resp->pop_back();
    return *resp == "ok";
  };
  return try_key(key_colon) || try_key(key_slash);
}

